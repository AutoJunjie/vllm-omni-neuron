"""Autoregressive think / recaption generation for HunyuanImage-3.0 on Neuron.

With ``bot_task`` ``think``, ``recaption`` or ``think_recaption`` the model first writes
text -- a chain of thought and/or a rewritten prompt -- and the image is then generated
conditioned on the prompt plus that text. Upstream vLLM-Omni runs the two as separate
stages on separate devices (an LLM stage, then the DiT stage, joined by a connector).
Here they share one backbone: the 32 decoder layers are already resident on every rank
for the DiT, so the text is generated by the same weights, on the same cores, before the
denoise loop starts.

The generation is greedy, as upstream's ``deploy/hunyuan_image3_ar.yaml`` runs it
(``temperature: 0.0``), and follows the same protocol: the prompt is built by
``prompt_utils.build_prompt_tokens`` (system prompt, ``User:``/``Assistant:`` turns and
the trigger tag), the stop tokens come from ``resolve_stop_token_ids``, ``</think>`` is
followed by a forced ``<recaption>``, and the text handed to the DiT is truncated at the
closing tag, as ``ar2diffusion`` does.

Execution is two static graphs:

* the existing prompt prefill, over the prompt minus its last token, which yields every
  layer's prompt K/V; and
* a one-token decode step, replayed per generated token. Its K/V cache for generated
  tokens is a fixed ``[1, max_new_tokens, kv_heads, head_dim]`` buffer per layer, updated
  as ``cache * (1 - onehot) + new * onehot`` -- exact for a one-hot, and a pure
  elementwise expression rather than an in-graph slice write, which is the construct
  that broke ``neuronx-cc``'s MaskPropagation pass in this backbone's MoE. The step's
  position, its RoPE row and the visible key range all arrive as inputs, so the graph
  never changes shape.

The decode MoE evaluates the rank's local experts densely: for one token the blockwise
kernel would pad to a whole 1024-row block. The LM head is vocab-parallel (each rank
holds ``vocab / tp`` rows) and one all-reduce of the zero-padded shards gives every rank
the full logits, so every rank takes the same greedy decision with no extra broadcast.
"""

import json
import logging
import os
import time

import torch
import torch.distributed as dist
import torch.nn.functional as F

from vllm_omni_neuron.diffusion.models.hunyuan_image3.hunyuan_image3_transformer import (
    _masked_attend,
    repeat_kv,
    rms_norm,
)

logger = logging.getLogger(__name__)

_MASK_BIAS = -1.0e30
AR_BOT_TASKS = ("think", "recaption", "think_recaption")


def _moe_dense(mlp, hidden_states: torch.Tensor) -> torch.Tensor:
    """``NeuronHunyuanMoE.forward`` with the routed experts always on the dense path."""
    bsz, seq, hidden = hidden_states.shape
    tokens = hidden_states.reshape(bsz * seq, hidden)
    weights = mlp._routing_weights(tokens).to(hidden_states.dtype)
    output = mlp._routed_experts_torch(tokens, weights)
    if mlp.num_shared_expert:
        shared_tokens = tokens.unsqueeze(0)
        gated = F.silu(torch.matmul(shared_tokens, mlp.shared_gate_weight)) * torch.matmul(
            shared_tokens, mlp.shared_up_weight
        )
        output = output + torch.matmul(gated, mlp.shared_down_weight).squeeze(0)
    if mlp.tp_size > 1:
        dist.all_reduce(output, group=mlp.tp_group)
    return output.reshape(bsz, seq, hidden)


class NeuronHunyuanImage3AR:
    """Greedy text generation on the DiT pipeline's own backbone. Every rank runs it."""

    def __init__(self, pipeline, model_path: str, max_new_tokens: int, compile_kwargs=None):
        self.pipeline = pipeline
        self.model = pipeline.model
        self.device = pipeline.device
        self.dtype = self.model.dtype
        self.max_new_tokens = int(max_new_tokens)
        config = pipeline.hf_config
        self.vocab_size = int(config.vocab_size)
        self.eps = float(config.rms_norm_eps)
        self.rope_theta = float(getattr(config, "rope_theta", 10000.0))
        self.head_dim = int(config.attention_head_dim)
        attn = self.model.layers[0].self_attn
        self.num_kv_heads = attn.num_kv_heads
        self.tp_size = self.model.tp_size
        self.tp_rank = self.model.tp_rank
        self.tp_group = self.model.tp_group
        if self.vocab_size % self.tp_size:
            raise ValueError(f"vocab_size {self.vocab_size} is not divisible by tp {self.tp_size}")
        self.vocab_shard = self.vocab_size // self.tp_size
        self.vocab_start = self.tp_rank * self.vocab_shard

        start = time.perf_counter()
        ln_f, lm_head = self._load_head(model_path)
        self.ln_f_weight = ln_f.to(self.dtype).to(self.device)
        # [H, V/tp], so the step is one matmul with no transpose in the graph.
        self.lm_head_t = lm_head.to(self.dtype).t().contiguous().to(self.device)
        logger.info(
            "HunyuanImage3 AR: LM head shard [%d:%d) of %d loaded in %.1fs",
            self.vocab_start,
            self.vocab_start + self.vocab_shard,
            self.vocab_size,
            time.perf_counter() - start,
        )

        tokenizer = pipeline._tkwrapper.tokenizer
        self.tokenizer = tokenizer
        self.eos_token_id = int(tokenizer.eos_token_id)
        ids = tokenizer.convert_tokens_to_ids
        self.end_think_id = ids("</think>")
        self.recaption_id = ids("<recaption>")
        self.end_recaption_id = ids("</recaption>")

        self._decode = self._decode_step
        if compile_kwargs is not None:
            args, options, kwargs = compile_kwargs
            self._decode = torch.compile(
                self._decode_step,
                *args,
                options={**options, "model_name": "hunyuan_image3_ar_decode"},
                **kwargs,
            )

    def _load_head(self, model_path: str):
        """``model.ln_f`` in full and this rank's rows of ``lm_head`` (untied from ``wte``)."""
        from safetensors import safe_open

        with open(os.path.join(model_path, "model.safetensors.index.json")) as handle:
            weight_map = json.load(handle)["weight_map"]
        with safe_open(
            os.path.join(model_path, weight_map["model.ln_f.weight"]), framework="pt", device="cpu"
        ) as f:
            ln_f = f.get_tensor("model.ln_f.weight")
        with safe_open(
            os.path.join(model_path, weight_map["lm_head.weight"]), framework="pt", device="cpu"
        ) as f:
            rows = f.get_slice("lm_head.weight")
            lm_head = rows[self.vocab_start : self.vocab_start + self.vocab_shard]
        return ln_f, lm_head

    # ---- graph ---------------------------------------------------------------

    def _decode_step(self, hidden_states, cos, sin, key_bias, onehot, *kv):
        """One token through all layers. ``kv`` is the prompt K/V then the generated K/V.

        Returns the full-vocabulary float32 logits and every layer's updated generated K/V.
        """
        num_layers = len(self.model.layers)
        prompt_kv, gen_kv = kv[: 2 * num_layers], kv[2 * num_layers :]
        keep = 1 - onehot
        updated = []
        for index, layer in enumerate(self.model.layers):
            attn = layer.self_attn
            residual = hidden_states
            normed = rms_norm(hidden_states, layer.input_layernorm_weight, layer.eps)
            query, key, value = attn._project(normed, cos, sin)
            gen_key = gen_kv[2 * index] * keep + key * onehot
            gen_value = gen_kv[2 * index + 1] * keep + value * onehot
            keys = torch.cat((prompt_kv[2 * index], gen_key), dim=1)
            values = torch.cat((prompt_kv[2 * index + 1], gen_value), dim=1)
            attended = _masked_attend(
                query.transpose(1, 2),
                repeat_kv(keys, attn.num_kv_groups).transpose(1, 2),
                repeat_kv(values, attn.num_kv_groups).transpose(1, 2),
                attn.scale,
                key_bias,
            )
            hidden_states = residual + attn._finish(attended)
            residual = hidden_states
            normed = rms_norm(hidden_states, layer.post_attention_layernorm_weight, layer.eps)
            hidden_states = residual + _moe_dense(layer.mlp, normed)
            updated.append(gen_key)
            updated.append(gen_value)

        final = rms_norm(hidden_states, self.ln_f_weight, self.eps)
        local = torch.matmul(final, self.lm_head_t).reshape(1, self.vocab_shard).float()
        logits = F.pad(
            local, (self.vocab_start, self.vocab_size - self.vocab_start - self.vocab_shard)
        )
        if self.tp_size > 1:
            dist.all_reduce(logits, group=self.tp_group)
        return (logits, *updated)

    # ---- host loop -------------------------------------------------------------

    def _rope(self, length: int):
        """Text-only 2D RoPE (both axes on the token index), as upstream builds it."""
        from vllm_omni.diffusion.models.hunyuan_image3.hunyuan_image3_transformer import (
            build_batch_2d_rope,
        )

        cos, sin = build_batch_2d_rope(
            seq_len=length,
            n_elem=self.head_dim,
            image_infos=[[]],
            device=torch.device("cpu"),
            base=self.rope_theta,
        )
        return cos.float(), sin.float()

    def generate(self, prompt: str, bot_task: str, system_prompt: str | None = None) -> dict:
        """Generate the think / recaption text for ``prompt``. Returns text, ids and timings."""
        from vllm_omni.diffusion.models.hunyuan_image3.prompt_utils import (
            build_prompt_tokens,
            resolve_stop_token_ids,
        )

        if bot_task not in AR_BOT_TASKS:
            raise ValueError(f"AR bot_task must be one of {AR_BOT_TASKS}, got {bot_task!r}")
        built = build_prompt_tokens(
            prompt,
            self.tokenizer,
            task="t2i",
            bot_task=bot_task,
            custom_system_prompt=system_prompt,
        )
        prompt_ids = list(built.token_ids)
        # An explicit size: the AR stops at the closing tag rather than predicting a ratio.
        stop_ids = set(
            resolve_stop_token_ids(task="t2i", bot_task=bot_task, image_size="1024x1024")
        )
        stop_ids.add(self.eos_token_id)
        transitions = (
            {self.end_think_id: self.recaption_id} if bot_task == "think_recaption" else {}
        )

        prefill_len = self.pipeline.prefill_len
        context = len(prompt_ids) - 1
        if context > prefill_len:
            raise ValueError(
                f"AR prompt needs {context} prefill tokens but prefill_len={prefill_len}"
            )
        budget = self.max_new_tokens
        cos, sin = self._rope(len(prompt_ids) + budget)

        start = time.perf_counter()
        prompt_tensor = torch.tensor([prompt_ids], dtype=torch.long)
        embeds, prompt_cos, prompt_sin = self.pipeline._prompt_inputs(
            prompt_tensor, cos, sin, context
        )
        prompt_kv = self.model.run_prefill(embeds, prompt_cos, prompt_sin)
        cache_shape = (1, budget, self.num_kv_heads, self.head_dim)
        gen_kv = [
            torch.zeros(cache_shape, dtype=self.dtype).to(self.device)
            for _ in range(2 * len(self.model.layers))
        ]
        prefill_seconds = time.perf_counter() - start

        visible = torch.full((1, 1, 1, prefill_len + budget), _MASK_BIAS, dtype=torch.float32)
        visible[..., :context] = 0.0
        generated: list[int] = []
        current = prompt_ids[-1]
        decode_start = time.perf_counter()
        first_token_seconds = None
        for step in range(budget):
            position = context + step
            hidden = self.pipeline.wte(torch.tensor([[current]])).to(self.dtype).to(self.device)
            step_cos = cos[:, position : position + 1].contiguous().to(self.device)
            step_sin = sin[:, position : position + 1].contiguous().to(self.device)
            visible[..., prefill_len + step] = 0.0
            onehot = torch.zeros((1, budget, 1, 1), dtype=self.dtype)
            onehot[0, step] = 1
            logits, *gen_kv = self._decode(
                hidden,
                step_cos,
                step_sin,
                visible.to(self.device),
                onehot.to(self.device),
                *prompt_kv,
                *gen_kv,
            )
            logits = logits.cpu()
            forced = transitions.get(generated[-1]) if generated else None
            token = forced if forced is not None else int(torch.argmax(logits[0]).item())
            if step == 0:
                first_token_seconds = time.perf_counter() - decode_start
            generated.append(token)
            if token in stop_ids:
                break
            current = token
        decode_seconds = time.perf_counter() - decode_start

        text = self.tokenizer.decode(generated, skip_special_tokens=False)
        for marker in ("</recaption>", "</think>"):
            index = text.find(marker)
            if index != -1:
                text = text[: index + len(marker)]
                break
        steps = len(generated)
        return {
            "text": text,
            "token_ids": generated,
            "prompt_tokens": len(prompt_ids),
            "generated_tokens": steps,
            "prefill_seconds": prefill_seconds,
            "first_token_seconds": first_token_seconds,
            "decode_seconds": decode_seconds,
            # The first step includes the decode graph's load (or compile).
            "seconds_per_token": (
                (decode_seconds - first_token_seconds) / (steps - 1) if steps > 1 else None
            ),
            "stopped": bool(generated) and generated[-1] in stop_ids,
        }
